// UTF-8 tables for src/utf8.ts (written by scripts/build.ts to
// image/utf8.gen.d.ts, git-ignored: ~6 MB, a `.d.ts` loaded lazily and only
// for sources or outputs with a non-ASCII character).
//
// tsrs splits template literal types by code point, so a character of a
// source text is one BMP character or one astral code point. The encoder
// table covers U+0080..U+1FFFF (BMP and plane 1, which holds the emoji)
// without the surrogates; any other code point encodes as U+FFFD.
//
//   EncB, EncA: character -> its UTF-8 bytes (a byte string: chars
//               U+0000..U+00FF); BMP and plane 1
//   DecB, DecA: UTF-8 byte sequence -> character (their inverses)
//   Lead: a lead byte -> the number of continuation bytes ("1".."3")
//
//   node scripts/gen-utf8.ts [out]
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { root } from "./inputs.ts";

/** A type-level string literal's source text: printable ASCII as is, everything else escaped. */
export function lit(s: string): string {
  let o = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0)!;
    if (c === 0x22) o += '\\"';
    else if (c === 0x5c) o += "\\\\";
    else if (c >= 0x20 && c < 0x7f) o += ch;
    else if (c < 0x100) o += "\\x" + c.toString(16).padStart(2, "0");
    else o += `\\u{${c.toString(16)}}`;
  }
  return o + '"';
}

const bytes = (cp: number) => Buffer.from(String.fromCodePoint(cp), "utf8").toString("latin1");

export function utf8Tables(): string {
  // two tables per direction: `keyof` of an interface with more than 100,000
  // keys is "a union type that is too complex to represent" (TS2590)
  const encB: string[] = [];
  const encA: string[] = [];
  const decB: string[] = [];
  const decA: string[] = [];
  for (let cp = 0x80; cp <= 0x1ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const b = bytes(cp);
    const ch = String.fromCodePoint(cp);
    (cp < 0x10000 ? encB : encA).push(`  ${lit(ch)}: ${lit(b)};`);
    (cp < 0x10000 ? decB : decA).push(`  ${lit(b)}: ${lit(ch)};`);
  }
  const lead: string[] = [];
  for (let b = 0xc2; b <= 0xf4; b++)
    lead.push(`  ${lit(String.fromCharCode(b))}: "${b < 0xe0 ? 1 : b < 0xf0 ? 2 : 3}";`);
  const table = (name: string, doc: string, rows: string[]) => [
    `/** ${doc} */`,
    `export interface ${name} {`,
    ...rows,
    "}",
  ];
  return [
    "// Generated by scripts/gen-utf8.ts (scripts/build.ts); do not edit.",
    ...table("EncB", "A BMP character (U+0080..U+FFFF, no surrogates) to its UTF-8 bytes.", encB),
    ...table("EncA", "A plane 1 character (U+10000..U+1FFFF) to its UTF-8 bytes.", encA),
    ...table("DecB", "Two or three UTF-8 bytes to the BMP character (EncB's inverse).", decB),
    ...table("DecA", "Four UTF-8 bytes to the plane 1 character (EncA's inverse).", decA),
    ...table("Lead", "A lead byte to its number of continuation bytes.", lead),
    "",
  ].join("\n");
}

export const utf8Path = join(root, "image/utf8.gen.d.ts");

if (import.meta.main) {
  const out = process.argv[2] ?? utf8Path;
  const text = utf8Tables();
  writeFileSync(out, text);
  console.log(`${out}: ${(text.length / 1e6).toFixed(1)} MB`);
}
