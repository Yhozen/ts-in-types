// Tables for src/hover.ts (`node scripts/gen-hover.ts` -> src/hover.gen.ts):
// a type-level Pearson hash of the source picks where in the fuel pool a
// hover's run starts, so that different checks in one editor session do not
// reuse each other's (already resolved, hence useless) pool nodes.
// (Adapted from ts-in-lua-in-types' scripts/gen-hover.ts.)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { root } from "./inputs.ts";

/** Chunks of the engine's fuel pool (go-in-types src/emit/fuel.gen.ts). */
export const POOL = 20000;
/** Hash values: two 6-bit Pearson hashes. */
const H = 64;

// xorshift32, fixed seed: the tables never change unless this file does.
let seed = 0x9e3779b9;
const rnd = () => {
  seed ^= seed << 13;
  seed >>>= 0;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  seed >>>= 0;
  return seed;
};
const perm = (n: number) => {
  const p = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = rnd() % (i + 1);
    [p[i], p[j]] = [p[j]!, p[i]!];
  }
  return p;
};

/** go-in-types' int encoding (nibbles, least significant first) of n >= 0: the pool's keys. */
export function encNat(n: number): string {
  let s = "";
  do {
    s += (n & 15).toString(16);
    n >>>= 4;
  } while (n > 0);
  return parseInt(s.at(-1)!, 16) >= 8 ? s + "0" : s;
}

const lit = JSON.stringify;
const obj = (entries: [string, string][]) =>
  `{ ${entries.map(([k, v]) => `${lit(k)}: ${lit(v)}`).join("; ")} }`;

/** One character U+0000..U+00FF to 0..63. */
const code = Array.from({ length: 256 }, () => rnd() % H);
/** Pearson step tables: M[h][c] = T[h xor c]. */
const step = () => {
  const t = perm(H);
  return Array.from({ length: H }, (_, h) =>
    obj(Array.from({ length: H }, (_, c) => [String(c), String(t[h ^ c])])),
  );
};
const table = (name: string, doc: string, rows: string[]) =>
  `/** ${doc} */\nexport interface ${name} {\n${rows.map((r, h) => `  ${lit(String(h))}: ${r};`).join("\n")}\n}\n`;
const m1 = step();
const m2 = step();
// starts spread over the pool, leaving room at its end for a long run
const stride = Math.floor((POOL - 1500) / (H * H));
const starts = Array.from({ length: H }, (_, h1) =>
  obj(Array.from({ length: H }, (_, h2) => [String(h2), encNat((h1 * H + h2) * stride)])),
);

const text = `// Generated by scripts/gen-hover.ts; do not edit.

/** A character (U+0000..U+00FF) to 0..63. */
export interface Code ${obj(code.map((c, i) => [String.fromCharCode(i), String(c)]))}
${table("M1", "Pearson step of the first hash: M1[h][code] = T1[h xor code].", m1)}
${table("M2", "Pearson step of the second hash.", m2)}
${table("KStart", `The fuel-pool chunk a run with hashes [h1, h2] starts at (an int): ${stride} * (64 * h1 + h2).`, starts)}`;

if (import.meta.main) {
  writeFileSync(join(root, "src/hover.gen.ts"), text);
  console.log(`src/hover.gen.ts: stride ${stride}`);
}
