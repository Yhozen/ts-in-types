// tsc in types from a terminal: runs a source through the compiler in types
// (src/index.ts) with the tsrs CLI, one TSStep per statement, and prints what
// tsc printed (stdout, decoded from UTF-8) and the exit status.
//
//   node scripts/tsc.ts [--lib es5|mini] [--chunks N] (--file main.ts | "source")
//
// The run's statements start at --chunks (default 400) and grow 4x while the
// run is unfinished. Writes .run/tsc/run.ts; stats go to stderr.
import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { lit } from "./gen-utf8.ts";
import { type Lib, root } from "./inputs.ts";
import { diagnostics, instCount, parsePrinted, runTsrs, writeProject } from "./types-gate.ts";

const argv = process.argv.slice(2);
const opt = (k: string) => (argv.includes(k) ? argv[argv.indexOf(k) + 1] : undefined);
const lib = (opt("--lib") ?? "es5") as Lib;
const file = opt("--file");
const valued = ["--lib", "--chunks", "--file"];
const positional = argv.filter((a, i) => !a.startsWith("--") && !valued.includes(argv[i - 1]!));
const source = file ? readFileSync(file, "utf8") : positional[0];
if (source === undefined) {
  console.error(
    'usage: node scripts/tsc.ts [--lib es5|mini] [--chunks N] (--file f.ts | "source")',
  );
  process.exit(64);
}
const dir = join(root, ".run/tsc");
const idx = relative(dir, join(root, "src/index.ts"));
let chunks = Number(opt("--chunks") ?? 400);
for (let attempt = 0; ; attempt++) {
  const lines = [
    "// Generated by scripts/tsc.ts; do not edit.",
    `import type { TSResult, TSStart, TSStep } from "${idx}";`,
    `type S0 = TSStart<${lit(source)}, "${lib}">;`,
  ];
  for (let k = 1; k <= chunks; k++) lines.push(`type S${k} = TSStep<S${k - 1}>;`);
  // stdout, stderr and the exit status in statements of their own: decoding
  // a long output can take most of a statement's instantiation budget
  const outLine = lines.length + 1;
  for (let i = 0; i < 3; i++)
    lines.push(`export const out${i}: "probe" = null! as [TSResult<S${chunks}>[${i}]];`);
  writeProject(dir, lines.join("\n") + "\n");
  const t = await runTsrs(dir, 3600);
  const ds = diagnostics(t.out);
  const outs = [0, 1, 2].map((i) => ds.find((x) => x.line === outLine + i));
  const vals = outs.map((d) => {
    const m = d && /^Type '\[([\s\S]*)\]' is not assignable to type '"probe"'\.$/.exec(d.message);
    return m ? parsePrinted(m[1]!) : undefined;
  });
  const ok = vals.every((v) => typeof v === "string" || typeof v === "number");
  const stats = `${(instCount(t.out) / 1e6).toFixed(1)}M instantiations, check ${/Check time:\s+([\d.]+)s/.exec(t.out)?.[1]} s, wall ${t.wall.toFixed(1)} s, peak ${(t.peak / 2 ** 30).toFixed(2)} GB, ${chunks} statements`;
  const other = ds.filter((x) => !outs.includes(x));
  if (!ok || other.length > 0) {
    console.error(
      `no result (${stats}): ${other.map((x) => `${x.code} ${x.message.slice(0, 200)}`).join("; ") || "the state is any or never"}`,
    );
    process.exit(2);
  }
  const [out, err, exit] = vals as [string, string, number];
  if (exit === -1 && attempt < 3) {
    chunks *= 4;
    continue;
  }
  process.stdout.write(Buffer.from(out, "latin1"));
  if (err) process.stderr.write(Buffer.from(err, "latin1"));
  console.error(exit === -1 ? `(still running) ${stats}` : `[exit ${exit}] ${stats}`);
  process.exitCode = exit === -1 ? 2 : exit;
  break;
}
