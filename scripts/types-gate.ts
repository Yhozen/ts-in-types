/** Statements for a run of n reference ops: ~1,800 ops per chunk on the one-liner, with headroom. */
export const estimateChunks = (ops: number): number => Math.ceil(ops / 1200) + 10;

const exitOf = (want: string) => Number(/\n\[exit (-?\d+)\]\n$/.exec(want)![1]);
const stdoutOf = (want: string) => want.slice(0, want.lastIndexOf("\n[exit "));

export function cliText(dir: string, source: string, lib: Lib, chunks: number, want: string) {
  const idx = relative(dir, join(root, "src/index.ts")).replaceAll("\\", "/");
  const lines = [
    "// Generated by scripts/types-gate.ts; do not edit.",
    `import type { TSResult, TSStart, TSStep } from "${idx}";`,
    "type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;",
    `type S0 = TSStart<${lit(source)}, "${lib}">;`,
  ];
  const firstStmt = lines.length + 1;
  for (let k = 1; k <= chunks; k++) lines.push(`type S${k} = TSStep<S${k - 1}>;`);
  const probeLine = lines.length + 1;
  for (let k = 1; k <= chunks; k++)
    lines.push(`export const p${k}: "probe" = null! as TSResult<S${k}>[2];`);
  const outLine = lines.length + 1;
  lines.push(`export const out: "probe" = null! as TSResult<S${chunks}>;`);
  lines.push(
    `export const ok: Equal<TSResult<S${chunks}>, [${lit(stdoutOf(want))}, "", ${exitOf(want)}]> = true;`,
  );
  return { text: lines.join("\n") + "\n", firstStmt, probeLine, outLine };
}

export function writeProject(dir: string, text: string): void {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "run.ts"), text);
  writeFileSync(
    join(dir, "tsconfig.json"),
    JSON.stringify(
      {
        compilerOptions: {
          target: "esnext",
          lib: ["es2023"],
          module: "nodenext",
          moduleResolution: "nodenext",
          strict: true,
          noEmit: true,
          allowImportingTsExtensions: true,
          skipLibCheck: true,
          types: [],
        },
        files: ["run.ts"],
      },
      null,
      1,
    ) + "\n",
  );
}

// ---------------------------------------------------------------- tsrs

export interface TsrsRun {
  out: string;
  wall: number;
  peak: number;
  timedOut: boolean;
}

/** `tsrs --noEmit -p dir` in a heavy slot, with a timeout counted from when the slot is held. */
export function runTsrs(dir: string, timeoutSec: number): Promise<TsrsRun> {
  const t0 = performance.now();
  return new Promise((done, fail) => {
    const p = spawn(
      heavy,
      [
        "/usr/bin/time",
        "-l",
        tsrsBin,
        "--noEmit",
        "--fast",
        "--singleThreaded",
        "--extendedDiagnostics",
        "--pretty",
        "false",
        "--noErrorTruncation",
        "-p",
        dir,
      ],
      { env: { ...process.env, TSRS_FAST: "1" }, detached: true },
    );
    let timedOut = false;
    let started = 0;
    const poll = setInterval(() => {
      if (started === 0 && spawnSync("pgrep", ["-P", String(p.pid)]).stdout.length > 0)
        started = performance.now();
      if (started > 0 && performance.now() - started > timeoutSec * 1000) {
        timedOut = true;
        try {
          process.kill(-p.pid!, "SIGKILL");
        } catch {
          // gone
        }
      }
    }, 500);
    let out = "";
    p.stdout.on("data", (d: Buffer) => (out += d.toString("latin1")));
    p.stderr.on("data", (d: Buffer) => (out += d.toString("latin1")));
    p.on("error", fail);
    p.on("close", () => {
      clearInterval(poll);
      const peak = Number(/(\d+)\s+maximum resident set size/.exec(out)?.[1] ?? 0);
      done({ out, wall: (performance.now() - t0) / 1000, peak, timedOut });
    });
  });
}

interface Diag {
  line: number;
  code: string;
  message: string;
}
/** run.ts diagnostics (a message may span lines). */
export function diagnostics(out: string): Diag[] {
  const ds: Diag[] = [];
  let cur: Diag | null = null;
  for (const l of out.split("\n")) {
    const m = /^(\S+)\((\d+),\d+\): error (TS\d+): (.*)$/.exec(l);
    if (m) {
      cur = m[1]!.endsWith("run.ts") ? { line: Number(m[2]), code: m[3]!, message: m[4]! } : null;
      if (cur) ds.push(cur);
    } else if (
      /^(Files|Lines|Identifiers|Symbols|Types|Instantiations|Memory used|\s+\d+ maximum)/.test(l)
    )
      cur = null;
    else if (cur) cur.message += "\n" + l;
  }
  return ds;
}
export const instCount = (out: string) => Number(/Instantiations:\s+(\d+)/.exec(out)?.[1] ?? NaN);
const assignMsg = /^Type '([\s\S]*)' is not assignable to type '"probe"'\.$/;

/** A printed type literal (string, number, tuple of those) back to plain values (latin1 strings). */
export function parsePrinted(t: string): any {
  let i = 0;
  const ws = () => {
    while (/\s/.test(t[i] ?? "")) i++;
  };
  const val = (): any => {
    ws();
    const c = t[i];
    if (c === "[") {
      i++;
      const xs: any[] = [];
      ws();
      while (t[i] !== "]") {
        xs.push(val());
        ws();
        if (t[i] === ",") i++;
        ws();
      }
      i++;
      return xs;
    }
    if (c === '"' || c === "'") {
      let o = "";
      i++;
      while (t[i] !== c) {
        let ch = t[i++]!;
        if (ch === "\\") {
          const e = t[i++]!;
          if (e === "x") {
            ch = String.fromCharCode(parseInt(t.slice(i, i + 2), 16));
            i += 2;
          } else if (e === "u") {
            if (t[i] === "{") {
              const j = t.indexOf("}", i);
              ch = String.fromCodePoint(parseInt(t.slice(i + 1, j), 16));
              i = j + 1;
            } else {
              ch = String.fromCharCode(parseInt(t.slice(i, i + 4), 16));
              i += 4;
            }
          } else
            ch =
              (
                { n: "\n", t: "\t", r: "\r", b: "\b", f: "\f", v: "\v", "0": "\0" } as Record<
                  string,
                  string
                >
              )[e] ?? e;
        }
        o += ch;
      }
      i++;
      return o;
    }
    const m = /^-?[\w.]+/.exec(t.slice(i))!;
    i += m[0].length;
    return /^-?\d/.test(m[0]) ? Number(m[0]) : { id: m[0] };
  };
  return val();
}

// ---------------------------------------------------------------- one check

interface Opts {
  timeoutSec: number;
  stamp: string;
}

async function runCheck(
  input: string,
  lib: Lib,
  ops: number,
  o: Opts,
  chunks0?: number,
): Promise<GateRow> {
  const dir = join(gateDir, lib, input);
  const source = readFileSync(join(inputsDir, input), "utf8");
  const want = readExpected(lib, input);
  let chunks = chunks0 ?? estimateChunks(ops);
  for (let attempt = 0; ; attempt++) {
    const r = await cliRun(dir, source, lib, chunks, want, ops, o);
    if (r.kind !== "unfinished" || chunks0 || attempt >= 2) return r;
    chunks *= 4;
  }
}

async function cliRun(
  dir: string,
  source: string,
  lib: Lib,
  chunks: number,
  want: string,
  ops: number,
  o: Opts,
): Promise<GateRow> {
  const c = cliText(dir, source, lib, chunks, want);
  writeProject(dir, c.text);
  const t = await runTsrs(dir, o.timeoutSec);
  writeFileSync(join(dir, "tsrs.log"), t.out);
  const input = relative(join(gateDir, lib), dir);
  const row: GateRow = {
    input,
    lib,
    pass: false,
    kind: "",
    chunks,
    lastGood: 0,
    instantiations: instCount(t.out),
    checkSeconds: Number(/Check time:\s+([\d.]+)s/.exec(t.out)?.[1] ?? NaN),
    wallSeconds: t.wall,
    peakBytes: t.peak,
    refOps: ops,
    stamp: o.stamp,
  };
  const exits = new Map<number, number>();
  let printed: any;
  let okFailed = false;
  const other: Diag[] = [];
  for (const d of diagnostics(t.out)) {
    const m = assignMsg.exec(d.message);
    if (d.line >= c.probeLine && d.line < c.outLine && m)
      exits.set(d.line - c.probeLine + 1, Number(m[1]));
    else if (d.line === c.outLine && m) printed = parsePrinted(m[1]!);
    else if (d.line === c.outLine + 1) okFailed = true;
    else other.push(d);
  }
  for (let k = 1; k <= chunks; k++) {
    const x = exits.get(k);
    if (x === undefined || Number.isNaN(x)) break;
    row.lastGood = k;
    if (x !== -1) {
      row.endedAt = k;
      break;
    }
  }
  const [stdout, stderr, exit] = Array.isArray(printed) ? printed : [];
  if (t.timedOut) return { ...row, kind: "timeout", detail: `killed after ${o.timeoutSec} s` };
  const stmtOf = (line: number) => line - c.firstStmt + 1;
  const deep = other.find((d) => d.code === "TS2589");
  if (deep) {
    const k = stmtOf(deep.line);
    return { ...row, ...(await classify2589(dir, source, lib, k, want, o.timeoutSec)) };
  }
  const full = other.find((d) => d.code === "TS2859");
  if (full) return { ...row, kind: "TS2859", detail: `statement ${stmtOf(full.line)}` };
  if (other.length > 0)
    return {
      ...row,
      kind: "other",
      detail: `${other.length} diagnostics; line ${other[0]!.line}: ${other[0]!.code} ${other[0]!.message.slice(0, 160)}`,
    };
  if (row.endedAt === undefined) {
    if (row.lastGood < chunks)
      return { ...row, kind: "any/never", detail: `statement ${row.lastGood + 1} is any or never` };
    return { ...row, kind: "unfinished", detail: `still running after ${chunks} statements` };
  }
  if (!okFailed) return { ...row, pass: true, kind: "pass" };
  const err = typeof stderr === "string" ? stderr : "";
  const trap = /trap: [^\n]*/.exec(err)?.[0];
  if (trap && /not kept \(--keep\)/.test(trap))
    return { ...row, kind: "not kept", detail: trap.slice(0, 200) };
  if (trap && /is not supported in types/.test(trap))
    return { ...row, kind: "unsupported", detail: trap.slice(0, 200) };
  if (trap) return { ...row, kind: "trap", detail: trap.slice(0, 200) };
  const got = encodeOut(
    typeof stdout === "string" ? stdout : "",
    typeof exit === "number" ? exit : -1,
  );
  return {
    ...row,
    kind: "wrong output",
    detail: err ? `stderr: ${err.split("\n")[0]!.slice(0, 160)}` : firstDiff(want, got),
  };
}

function firstDiff(want: string, got: string): string {
  const a = want.split("\n");
  const b = got.split("\n");
  for (let i = 0; i < Math.max(a.length, b.length); i++)
    if (a[i] !== b[i])
      return `line ${i + 1}: want ${JSON.stringify(a[i] ?? "").slice(0, 90)} got ${JSON.stringify(b[i] ?? "").slice(0, 90)}`;
  return "printed output matches; Equal failed";
}

/** TS2589 at statement k: statements 1..k minus 1..k-1 (two CLI runs); >= 4M is the count limit. */
async function classify2589(
  dir: string,
  source: string,
  lib: Lib,
  k: number,
  want: string,
  timeoutSec: number,
): Promise<{ kind: string; detail: string }> {
  const sub = async (n: number) => {
    const d = join(dir, `k${n}`);
    const c = cliText(d, source, lib, n, want);
    const text =
      c.text
        .split("\n")
        .slice(0, c.probeLine - 1)
        .join("\n") + "\n";
    writeProject(d, text);
    return runTsrs(d, timeoutSec);
  };
  const a = await sub(k - 1);
  const b = await sub(k);
  if (a.timedOut || b.timedOut)
    return { kind: "TS2589 depth", detail: `statement ${k}; the rerun timed out (unclassified)` };
  const cost = instCount(b.out) - instCount(a.out);
  return cost >= 4_000_000
    ? {
        kind: "TS2589 count",
        detail: `statement ${k} costs ${(cost / 1e6).toFixed(1)}M instantiations`,
      }
    : {
        kind: "TS2589 depth",
        detail: `statement ${k} fails after ${(cost / 1e6).toFixed(2)}M instantiations`,
      };
}

// ---------------------------------------------------------------- tiers

/** Inputs spread over the reference's op counts (mini), always with the one-liner and the Unicode ones. */
export function tierInputs(n: number, ops: Map<string, number>): string[] {
  const fixed = ["assign-basic.ts", "clean-unicode.ts", "error-unicode-position.ts"];
  const rest = listInputs()
    .filter((i) => !fixed.includes(i) && !i.startsWith("extreme/"))
    .sort((a, b) => (ops.get(`mini/${a}`) ?? 0) - (ops.get(`mini/${b}`) ?? 0) || (a < b ? -1 : 1));
  const m = n - fixed.length;
  // evenly spaced quantiles up to p90 (the slow tail belongs to the full gate)
  const picks = Array.from(
    { length: m },
    (_, i) => rest[Math.floor(((i + 0.5) / m) * rest.length * 0.9)]!,
  );
  return [...fixed, ...new Set(picks)];
}

// ---------------------------------------------------------------- report

const fmt = (n: number) => n.toLocaleString("en-US");
function quant(xs: number[]) {
  const s = [...xs].sort((a, b) => a - b);
  const q = (p: number) => s[Math.min(s.length - 1, Math.floor(p * s.length))] ?? 0;
  return [s[0] ?? 0, q(0.5), q(0.9), s.at(-1) ?? 0];
}

export function gateDoc(rows: GateRow[], args: string): string {
  const cat = (i: string) =>
    i.startsWith("upstream/") ? "upstream" : i.startsWith("extreme/") ? "extremes" : "hand-written";
  const cats = ["hand-written", "upstream", "extremes"];
  const libs = [...LIBS];
  const pass = (rs: GateRow[]) => `${rs.filter((r) => r.pass).length} / ${rs.length}`;
  const lines = [
    "# The types gate",
    "",
    `Generated by \`scripts/types-gate.ts\` (\`vp run gate:types -- ${args}\`); do not edit.`,
    "",
    "Every oracle input checked by the TypeScript 7 compiler inside tsrs (the image of `vp run build`, through `src/index.ts`, CLI chunks: one `TSStep` per statement), compared byte for byte with native tsc's stdout and exit status (`oracle/expected/`).",
    "",
    "## Pass rate",
    "",
    `| category | ${libs.join(" | ")} | both |`,
    `| --- | ${libs.map(() => "---:").join(" | ")} | ---: |`,
    ...cats.map(
      (c) =>
        `| ${c} | ${libs.map((l) => pass(rows.filter((r) => r.lib === l && cat(r.input) === c))).join(" | ")} | ${pass(rows.filter((r) => cat(r.input) === c))} |`,
    ),
    `| **all** | ${libs.map((l) => `**${pass(rows.filter((r) => r.lib === l))}**`).join(" | ")} | **${pass(rows)}** |`,
    "",
    "## Passing checks",
    "",
    "Min / median / p90 / max. Chunks: CLI statements to the end of the run; time: tsrs's check time; memory: max RSS; ratio: instantiations per reference op.",
    "",
    "| lib | n | reference ops | chunks | instantiations | check time | memory | inst / op |",
    "| --- | ---: | --- | --- | --- | --- | --- | --- |",
  ];
  for (const l of libs) {
    const ps = rows.filter((r) => r.lib === l && r.pass);
    if (ps.length === 0) continue;
    const q = (f: (r: GateRow) => number, u: (x: number) => string) =>
      quant(ps.map(f)).map(u).join(" / ");
    lines.push(
      `| ${l} | ${ps.length} | ${q(
        (r) => r.refOps,
        (x) => `${Math.round(x / 1000)}k`,
      )} | ${q((r) => r.endedAt ?? r.chunks, fmt)} | ${q(
        (r) => r.instantiations,
        (x) => `${(x / 1e6).toFixed(0)}M`,
      )} | ${q(
        (r) => r.checkSeconds,
        (x) => `${x.toFixed(1)} s`,
      )} | ${q(
        (r) => r.peakBytes,
        (x) => `${(x / 2 ** 30).toFixed(1)} GB`,
      )} | ${q(
        (r) => r.instantiations / r.refOps,
        (x) => fmt(Math.round(x)),
      )} |`,
    );
  }
  const fails = rows.filter((r) => !r.pass);
  const kinds = [...new Set(fails.map((r) => r.kind))].sort(
    (a, b) => fails.filter((r) => r.kind === b).length - fails.filter((r) => r.kind === a).length,
  );
  lines.push("", "## Failures", "");
  if (fails.length === 0) lines.push("None.");
  lines.push(
    `| class | ${libs.join(" | ")} |`,
    `| --- | ${libs.map(() => "---:").join(" | ")} |`,
    ...kinds.map(
      (k) =>
        `| ${k} | ${libs.map((l) => fails.filter((r) => r.kind === k && r.lib === l).length).join(" | ")} |`,
    ),
  );
  for (const k of kinds) {
    const rs = fails.filter((r) => r.kind === k).sort((a, b) => a.refOps - b.refOps);
    lines.push(
      "",
      `### ${k} (${rs.length})`,
      "",
      "| input | lib | reference ops | detail |",
      "| --- | --- | ---: | --- |",
      ...rs.map(
        (r) =>
          `| ${r.input} | ${r.lib} | ${fmt(r.refOps)} | ${(r.detail ?? "").replaceAll("|", "\\|").replaceAll("\n", " ")} |`,
      ),
    );
  }
  return lines.join("\n") + "\n";
}

// ---------------------------------------------------------------- main

async function main() {
  const argv = process.argv.slice(2);
  const opt = (k: string) => (argv.includes(k) ? argv[argv.indexOf(k) + 1] : undefined);
  const all = (k: string) => argv.flatMap((a, i) => (a === k ? [argv[i + 1]!] : []));
  const libs = (all("--lib") as Lib[]).filter((l) => LIBS.includes(l));
  const jobs = Math.min(2, Number(opt("--jobs") ?? 2));
  const timeoutSec = Number(opt("--timeout") ?? 600);
  const tier = argv.includes("--full") ? "full" : (opt("--tier") ?? "smoke");
  const only = all("--only");
  if (!existsSync(buildInfoPath)) throw new Error("no image/build.json: run vp run build first");
  const build = JSON.parse(readFileSync(buildInfoPath, "utf8"));
  const stamp = `${build.ir.digest}/${build.keep}/${build.bytes.program}`;
  const ops = await refOps(stamp);
  let inputs =
    only.length > 0
      ? listInputs(only)
      : tier === "full"
        ? listInputs()
        : tierInputs(tier === "20" ? 20 : 10, ops);
  inputs = [...new Set(inputs)];
  const checks = inputs.flatMap((input) =>
    (libs.length ? libs : [...LIBS]).map((lib) => ({ input, lib })),
  );
  // results of earlier runs
  const old: GateRow[] = existsSync(resultsPath)
    ? JSON.parse(readFileSync(resultsPath, "utf8"))
    : [];
  const key = (r: { lib: string; input: string }) => `${r.lib}/${r.input}`;
  const byKey = new Map(old.map((r) => [key(r), r]));
  const todo = checks.filter((c) => {
    const r = byKey.get(key(c));
    return !(argv.includes("--resume") && r && r.stamp === stamp);
  });
  // cheap first, so a timeout-bound tail does not hold up the rest
  todo.sort((a, b) => (ops.get(key(a)) ?? 0) - (ops.get(key(b)) ?? 0));
  console.log(
    `gate (${tier}): ${checks.length} checks, ${todo.length} to run, ${jobs} jobs, timeout ${timeoutSec} s`,
  );
  const t0 = performance.now();
  let done = 0;
  const save = () => {
    mkdirSync(dirname(resultsPath), { recursive: true });
    const rows = [...byKey.values()].sort((a, b) => (key(a) < key(b) ? -1 : 1));
    writeFileSync(resultsPath, JSON.stringify(rows, null, 0).replaceAll("},{", "},\n{") + "\n");
  };
  await pool(todo, jobs, async (c) => {
    const r = await runCheck(c.input, c.lib, ops.get(key(c)) ?? 0, { timeoutSec, stamp });
    byKey.set(key(c), r);
    save();
    done++;
    console.log(
      `${String(done).padStart(4)}/${todo.length} ${r.pass ? "PASS" : "FAIL"} ${c.lib} ${c.input}  ` +
        `${r.endedAt !== undefined ? `ended at ${r.endedAt}/${r.chunks}` : `reached ${r.lastGood}/${r.chunks}`}  ` +
        `${(r.instantiations / 1e6).toFixed(1)}M inst  check ${r.checkSeconds.toFixed(1)} s (wall ${r.wallSeconds.toFixed(1)} s)  ` +
        `peak ${(r.peakBytes / 2 ** 30).toFixed(2)} GB  ref ${fmt(r.refOps)} ops` +
        (r.pass ? "" : `  ${r.kind}: ${r.detail ?? ""}`),
    );
  });
  save();
  const rows = checks.map((c) => byKey.get(key(c))!).filter(Boolean);
  const pass = rows.filter((r) => r.pass).length;
  const kinds: Record<string, number> = {};
  for (const r of rows) if (!r.pass) kinds[r.kind] = (kinds[r.kind] ?? 0) + 1;
  console.log(
    `\n${pass}/${rows.length} pass (${((100 * pass) / Math.max(1, rows.length)).toFixed(1)}%) in ${((performance.now() - t0) / 1000).toFixed(0)} s` +
      (Object.keys(kinds).length ? `; ${JSON.stringify(kinds)}` : ""),
  );
  if (argv.includes("--doc")) {
    const args = argv.filter((a) => a !== "--resume").join(" ");
    writeFileSync(docPath, gateDoc(rows, args));
    console.log(`wrote ${docPath} (run vp check --fix to format it)`);
  }
  process.exitCode = pass === rows.length ? 0 : 1;
}

if (import.meta.main) await main();
