// The types gate: the compiler in types (the image of `vp run build`, via
// src/index.ts) must print exactly what native tsc 7.0.2 prints
// (oracle/expected/), checked with the tsrs CLI in chained chunks.
//
//   vp run gate:types                    smoke: 10 inputs, both libs (20 checks)
//   vp run gate:types -- --tier 20       20 inputs, both libs (40 checks)
//   vp run gate:types -- --full          all 328 inputs, both libs (656 checks)
//   vp run gate:types -- --only NAME     inputs whose path contains NAME (repeatable)
//   vp run gate:types -- --lib mini      one lib mode (repeatable; default both)
//   vp run gate:types -- --jobs 2        tsrs runs at once (at most 2: heavy.sh slots)
//   vp run gate:types -- --timeout 600   seconds per tsrs run (default 600)
//   vp run gate:types -- --resume        keep results of the same build
//   vp run gate:types -- --doc           write docs/GATE.md from the results (--full)
//
// Per check it writes .run/gate/<lib>/<input>/run.ts: `type S0 =
// TSStart<source, lib>`, one `type Sk = TSStep<Sk-1>` per statement (the CLI
// zeroes its instantiation counter per statement), a probe per statement
// (the exit status: -1 while running; nothing when the state is any or
// never), the result, and an exact equality with the oracle's
// [stdout, stderr, exit]. The number of statements comes from the
// reference's op count with headroom; an unfinished run is retried with 4x
// the statements, twice. tsrs runs through the engine's scripts/heavy.sh.
//
// Failure classes (GateRow.kind): "TS2589 count" / "TS2589 depth" (one
// statement over the 5M-instantiation budget, or a depth limit below it:
// told apart by rerunning statements 1..k-1 and 1..k), "TS2859" (relation
// cache full), "any/never" (a statement's state is any or never without a
// diagnostic), "unfinished", "timeout", "not kept" (the run called a
// function outside the build's keep list), "unsupported" (a feature the
// type level traps on), "trap" (another trap), "wrong output" (first
// differing line), "other" (any other diagnostic).
//
// Results: .run/gate/results.json (one row per check, with the build's
// stamp; --resume keeps rows of the same build), and with --doc docs/GATE.md.
import { spawn, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { buildInfoPath } from "./build.ts";
import { engineDir } from "./engine.ts";
import { lit } from "./gen-utf8.ts";
import { encodeOut, inputsDir, type Lib, LIBS, listInputs, readExpected, root } from "./inputs.ts";
import { pool } from "./pool.ts";
import { runChecks } from "./ref.ts";

const tsrsBin = join(root, "node_modules/.bin/tsrs");
const heavy = join(engineDir, "scripts/heavy.sh");
const gateDir = join(root, ".run/gate");
const resultsPath = join(gateDir, "results.json");
const docPath = join(root, "docs/GATE.md");

export interface GateRow {
  input: string;
  lib: Lib;
  pass: boolean;
  kind: string;
  detail?: string;
  /** statements written; the one at which the run ended; the last that resolved */
  chunks: number;
  endedAt?: number;
  lastGood: number;
  instantiations: number;
  checkSeconds: number;
  wallSeconds: number;
  peakBytes: number;
  refOps: number;
  stamp: string;
}

// ---------------------------------------------------------------- reference ops

/** The reference's op count per check from the boot images (cached per build). */
async function refOps(stamp: string): Promise<Map<string, number>> {
  const path = join(gateDir, "ref-ops.json");
  if (existsSync(path)) {
    const c = JSON.parse(readFileSync(path, "utf8"));
    if (c.stamp === stamp) return new Map(Object.entries(c.ops));
  }
  const ops: Record<string, number> = {};
  await runChecks({
    libs: [...LIBS],
    only: [],
    jobs: 6,
    mode: "image",
    cap: 20e9,
    profile: false,
    onResult: (job, r) => (ops[`${job.lib}/${job.input}`] = r.ops),
  });
  mkdirSync(gateDir, { recursive: true });
  writeFileSync(path, JSON.stringify({ stamp, ops }));
  return new Map(Object.entries(ops));
}

